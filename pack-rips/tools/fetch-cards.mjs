// Rebuilds js/cards.js from the TCGdex API (https://tcgdex.dev).
// Only facts are stored: card number, name, rarity and a market price snapshot of each
// printing. Card images are never downloaded; the game loads them from TCGdex at runtime.
// Printings worth less than MIN_VALUE are left out, since no pack can pay them out, and
// so are cards without an image.
//
//   node tools/fetch-cards.mjs            rebuild every set
//   node tools/fetch-cards.mjs sv03.5     rebuild some sets and keep the rest as they are
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const API = 'https://api.tcgdex.net/v2';
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'js', 'cards.js');
const SERIES = ['base', 'gym', 'neo', 'lc', 'ecard', 'ex', 'pop', 'dp', 'pl', 'hgss', 'col', 'bw', 'xy', 'sm', 'swsh', 'sv', 'me'];
const SKIP = /^(tk-|jumbo)/; // trainer kits and oversized cards
const MIN_VALUE = 0.1; // the cheapest pack's minimum card
const EUR_TO_USD = 1.1; // only used when a card has no US price
const FALLBACK_MAX = 100; // European prices above this are too often matched to the wrong product
const CONCURRENCY = 10;

async function getJSON(url, tries = 5) {
  for (let i = 0; ; i++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(res.status + ' ' + url);
      return await res.json();
    } catch (err) {
      if (i >= tries - 1) throw err;
      await new Promise(r => setTimeout(r, 800 * (i + 1)));
    }
  }
}

const round = n => Math.round(n * 100) / 100;

// Market price in USD of each printing of a card: n normal, h holo, r reverse holo,
// f 1st edition, F 1st edition holo.
function prices(card) {
  const out = {};
  const tcg = card.pricing && card.pricing.tcgplayer;
  if (tcg) {
    // The market price follows recent sales. One odd sale can throw it far above what
    // the card is listed for, so it is held to twice the mid listing price.
    const pick = k => {
      const { marketPrice: market, midPrice: mid } = tcg[k] || {};
      return market && mid && market > 2 * mid ? mid : market;
    };
    const found = {
      n: pick('normal') || pick('unlimited'),
      h: pick('holofoil') || pick('unlimited-holofoil'),
      r: pick('reverse-holofoil'),
      f: pick('1st-edition'),
      F: pick('1st-edition-holofoil'),
    };
    for (const k in found) if (found[k]) out[k] = round(found[k]);
  }
  if (!Object.keys(out).length) {
    const cm = card.pricing && card.pricing.cardmarket;
    const eur = cm && (cm.trend || cm.avg30 || cm.avg);
    if (eur && eur * EUR_TO_USD <= FALLBACK_MAX) out.n = round(eur * EUR_TO_USD);
  }
  for (const k in out) if (out[k] < MIN_VALUE) delete out[k];
  return out;
}

async function buildSet(id) {
  const set = await getJSON(`${API}/en/sets/${id}`);
  const rows = new Array(set.cards.length);
  let next = 0, img = null;
  async function worker() {
    while (next < set.cards.length) {
      const i = next++;
      let c;
      try {
        c = await getJSON(`${API}/en/cards/${encodeURIComponent(set.cards[i].id)}`);
      } catch (err) {
        console.log('  skipped ' + set.cards[i].id + ': ' + err.message);
        continue;
      }
      const p = prices(c);
      if (!c.image || !Object.keys(p).length) continue; // nothing to show or nothing to pay out
      // Images sit at <set folder>/<card number>, so the folder is stored once per set
      // and a card only carries its own address when it is somewhere else.
      const folder = c.image.endsWith('/' + c.localId) ? c.image.slice(0, -c.localId.length - 1) : null;
      img = img || folder;
      rows[i] = [c.localId, c.name, c.rarity || 'None', p].concat(folder && folder === img ? [] : [c.image]);
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  const cards = rows.filter(Boolean);
  console.log(`${id} ${set.name}: kept ${cards.length} of ${set.cards.length} cards`);
  return {
    id: set.id,
    name: set.name,
    series: set.serie && set.serie.name,
    released: set.releaseDate,
    size: set.cardCount.official,
    img,
    cards,
  };
}

async function existing() {
  try {
    const win = {};
    new Function('window', await readFile(OUT, 'utf8'))(win);
    return win.PACK_DATA;
  } catch (_) {
    return null;
  }
}

async function save(data) {
  data.sets.sort((a, b) => (a.released < b.released ? -1 : a.released > b.released ? 1 : 0));
  const body = data.sets.map(s => JSON.stringify(s)).join(',\n');
  await writeFile(OUT, '// Generated by tools/fetch-cards.mjs. Do not edit by hand.\n' +
    `window.PACK_DATA = {"priced":${JSON.stringify(data.priced)},"sets":[\n${body}\n]};\n`);
}

let wanted = process.argv.slice(2);
const data = (wanted.length && await existing()) || { sets: [] };
if (!wanted.length) {
  for (const s of SERIES) {
    const serie = await getJSON(`${API}/en/series/${s}`);
    wanted.push(...serie.sets.map(x => x.id).filter(id => !SKIP.test(id)));
  }
}
data.priced = new Date().toISOString().slice(0, 10);
for (const id of wanted) {
  try {
    const set = await buildSet(id);
    data.sets = data.sets.filter(s => s.id !== id);
    if (set.cards.length) data.sets.push(set);
    await save(data);
  } catch (err) {
    console.log(`${id}: FAILED ${err.message}`);
  }
}
const n = data.sets.reduce((sum, s) => sum + s.cards.length, 0);
console.log(`\n${data.sets.length} sets, ${n} cards worth $${MIN_VALUE.toFixed(2)} or more`);
