// Rebuilds js/sets/*.js from the TCGdex API (https://tcgdex.dev).
// Only facts are stored: card number, name, rarity, which printings exist and a
// market price snapshot. Card images are never downloaded; the game loads them
// from TCGdex at runtime.
//
//   node tools/fetch-sets.mjs            rebuild every set
//   node tools/fetch-sets.mjs sv03.5     rebuild one set
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const API = 'https://api.tcgdex.net/v2';
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'js', 'sets');
const SETS = ['base1', 'swsh7', 'sv03.5', 'sv08', 'sv08.5', 'sv10'];
const EUR_TO_USD = 1.1; // only used when a card has no US price
const CONCURRENCY = 6;

async function getJSON(url, tries = 4) {
  for (let i = 0; ; i++) {
    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(res.status + ' ' + url);
      return await res.json();
    } catch (err) {
      if (i >= tries - 1) throw err;
      await new Promise(r => setTimeout(r, 600 * (i + 1)));
    }
  }
}

const round = n => Math.round(n * 100) / 100;

// Market price in USD for each printing of a card: n normal, h holo, r reverse holo.
function prices(card) {
  const out = {};
  const tcg = card.pricing && card.pricing.tcgplayer;
  if (tcg) {
    const pick = k => tcg[k] && (tcg[k].marketPrice || tcg[k].midPrice);
    const n = pick('normal') || pick('unlimited') || pick('1st-edition');
    const h = pick('holofoil') || pick('unlimited-holofoil') || pick('1st-edition-holofoil');
    const r = pick('reverse-holofoil');
    if (n) out.n = round(n);
    if (h) out.h = round(h);
    if (r) out.r = round(r);
  }
  if (!Object.keys(out).length) {
    const cm = card.pricing && card.pricing.cardmarket;
    const eur = cm && (cm.trend || cm.avg30 || cm.avg);
    if (eur) out.n = round(eur * EUR_TO_USD);
  }
  return out;
}

async function buildSet(id) {
  const set = await getJSON(`${API}/en/sets/${id}`);
  const cards = new Array(set.cards.length);
  let next = 0;
  async function worker() {
    while (next < set.cards.length) {
      const i = next++;
      const c = await getJSON(`${API}/en/cards/${encodeURIComponent(set.cards[i].id)}`);
      const v = c.variants || {};
      cards[i] = {
        n: c.localId,
        name: c.name,
        r: c.rarity || 'None',
        cat: c.category,
        img: c.image || null,
        v: (v.normal ? 'n' : '') + (v.holo ? 'h' : '') + (v.reverse ? 'r' : ''),
        p: prices(c),
      };
    }
  }
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  const data = {
    id: set.id,
    name: set.name,
    series: set.serie && set.serie.name,
    released: set.releaseDate,
    official: set.cardCount.official,
    priced: new Date().toISOString().slice(0, 10),
    cards,
  };
  const js = '// Generated by tools/fetch-sets.mjs. Do not edit by hand.\n' +
    `(window.PACK_SETS = window.PACK_SETS || {})[${JSON.stringify(id)}] = ${JSON.stringify(data)};\n`;
  await writeFile(path.join(OUT, id + '.js'), js);
  const unpriced = cards.filter(c => !Object.keys(c.p).length).length;
  const noImg = cards.filter(c => !c.img).length;
  console.log(`${id} ${set.name}: ${cards.length} cards, ${unpriced} without a price, ${noImg} without an image`);
}

const wanted = process.argv.slice(2);
for (const id of wanted.length ? wanted : SETS) await buildSet(id);
