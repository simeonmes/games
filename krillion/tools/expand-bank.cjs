// Compile reviewed supplements after the existing banks. No network needed.
// node krillion/tools/expand-bank.cjs
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const root = path.join(__dirname, '..');
const htmlPath = path.join(root, 'index.html');
let html = fs.readFileSync(htmlPath, 'utf8');
const scripts = [...html.matchAll(/src="(js\/[^"?]+\.js)/g)].map(m => m[1])
  .filter(f => !['main', 'room', 'audio', 'scene', 'bank-expanded'].some(name => f === `js/${name}.js`));
const ctx = vm.createContext({ console });
vm.runInContext(scripts.map(f => fs.readFileSync(path.join(root, f), 'utf8')).join('\n') + ';this.api = {PROMPTS, Match, tiersFor};', ctx);
const { PROMPTS, Match, tiersFor } = ctx.api;
const source = JSON.parse(fs.readFileSync(path.join(__dirname, 'data/answer-supplement.json'), 'utf8'));
const original = JSON.parse(fs.readFileSync(path.join(__dirname, 'data/answer-baseline.json'), 'utf8'));
const out = {}, report = [];
// Match the bank verifier's suffix checks; variants belong to the existing answer.
const suffixes = ['moon','dwarfplanet','cheese','bone','bones','nut','nuts','pasta','fish','vertebra','noodle','fruit','hat','cap','bonnet','lizard','shark','spider','dog','root','gland','glands','stone','steak','cut','lettuce','squash','mushroom','bean','beans','pepper','onion','potato','apple','orange','lemon','berry','tree','frog','turtle','snake','bird','parrot','owl','eagle','wombat','possum','kangaroo','wallaby','terrier','hound','spaniel','retriever','shepherd','mastiff','pointer','setter','sheepdog','drum','drums','guitar','horn','flute','pipe','pipes','harp','organ','piano','saxophone','karate','kungfu','jitsu','wrestling','boxing','sword'];
for (const [pi, [q]] of PROMPTS.entries()) {
  if (!source[q]) throw new Error(`Missing supplement for ${q}`);
  const bank = Match.build(tiersFor(pi));
  const before = original[q];
  const additions = {};
  for (const [tier, answers] of Object.entries(source[q])) for (const raw of answers.split('|')) {
    const names = raw.split('/').map(s => s.trim()).filter(Boolean);
    const known = names.map(n => bank.index.get(Match.key(n))).filter(Boolean);
    let entry = known[0];
    if (!entry) {
      const k = Match.key(names[0]);
      for (const suffix of suffixes) {
        if (k.length > suffix.length && k.endsWith(suffix) && bank.index.has(k.slice(0, -suffix.length))) {
          entry = bank.index.get(k.slice(0, -suffix.length)); break;
        }
      }
    }
    if (!entry) {
      const k = Match.key(names[0]);
      const longer = [...new Set(suffixes.map(suffix => bank.index.get(k + suffix)).filter(Boolean))];
      if (longer.length === 1) entry = longer[0];
    }
    const fresh = names.filter(n => Match.key(n) && !bank.index.has(Match.key(n)));
    if (!fresh.length) continue;
    const t = entry ? entry.tier : tier;
    const shown = entry ? entry.shown : names[0];
    const spellings = [...new Set([shown, ...fresh])];
    (additions[t] ||= []).push(spellings.join('/'));
    entry ||= { shown, tier: t };
    for (const name of spellings) if (!bank.index.has(Match.key(name))) bank.index.set(Match.key(name), entry);
    if (!bank.entries.includes(entry)) bank.entries.push(entry);
  }
  out[q] = Object.fromEntries(Object.entries(additions).map(([t, values]) => [t, values.join('|')]));
  const newKeys = [...bank.index.keys()].filter(k => !before.keys.includes(k));
  report.push({ prompt: q, before: before.answers, after: bank.entries.length, addedAnswers: bank.entries.length - before.answers, addedSpellings: newKeys.length });
}
fs.writeFileSync(path.join(root, 'js/bank-expanded.js'), `"use strict";\n// Generated by tools/expand-bank.cjs from tools/data/answer-supplement.json.\n// Reviewed additions and aliases. Existing answers retain their original scores.\nBANK_SOURCES.push(${JSON.stringify(out, null, 2)});\n`);
if (!html.includes('bank-expanded.js')) {
  html = html.replace(/(<script src="js\/match\.js[^\"]*"><\/script>)/, '<script src="js/bank-expanded.js?v=1"></script>\n$1');
  fs.writeFileSync(htmlPath, html);
}
fs.writeFileSync(path.join(__dirname, 'data/answer-coverage.json'), JSON.stringify(report, null, 2) + '\n');
console.log(`${report.length} prompts; ${report.reduce((n,p) => n+p.addedAnswers,0)} new answers; ${report.reduce((n,p) => n+p.addedSpellings,0)} additional accepted spellings.`);
const gaps = report.filter(p => !p.addedSpellings);
if (gaps.length) { console.log('Unchanged prompts:', gaps.map(p => p.prompt).join('\n')); process.exitCode = 1; }
